ASSETS = Path(__file__).with_name('astryx_assets')


class AstryxContent(BaseModel):
    title: str = Field(default='Trabalho em equipe: juntos fazemos melhor', min_length=1, max_length=160)
    subtitle: str = Field(default='Aprenda a colaborar com clareza, respeito e propósito.', max_length=300)
    heading: str = Field(default='Colaborar é conectar pessoas e responsabilidades', min_length=1, max_length=180)
    body: str = Field(default='Uma equipe reúne habilidades complementares para alcançar um objetivo comum.\nCombine responsabilidades e prazos.\nCompartilhe dúvidas e ofereça apoio.\nRevise os resultados com respeito e escuta.', min_length=1, max_length=4000)
    image: str = Field(default='', max_length=2800000)
    imageAlt: str = Field(default='Ilustração de pessoas conectadas por um objetivo comum', max_length=300)
    question: str = Field(default='Uma colega está com dificuldade para concluir uma entrega. Qual atitude favorece a colaboração?', min_length=1, max_length=600)
    options: list[str] = Field(default_factory=lambda: ['Oferecer apoio e combinar as próximas ações.', 'Ignorar a dificuldade e seguir sozinho.', 'Cobrar o resultado sem ouvir a colega.'], min_length=3, max_length=3)
    correct: int = Field(default=0, ge=0, le=2)
    feedback: str = Field(default='Oferecer apoio e alinhar as próximas ações ajuda a equipe a alcançar o objetivo comum.', min_length=1, max_length=900)
    accent: Literal['blue', 'teal', 'violet'] = 'blue'
    appearance: Appearance = Field(default_factory=Appearance)

    @field_validator('title', 'heading', 'body', 'question', 'feedback')
    @classmethod
    def nonempty(cls, value):
        if not value.strip():
            raise ValueError('Preencha os campos obrigatórios.')
        return value.strip()

    @field_validator('options')
    @classmethod
    def valid_options(cls, values):
        if any(not v.strip() or len(v) > 400 for v in values):
            raise ValueError('Informe três alternativas, com até 400 caracteres cada.')
        if len({v.strip().casefold() for v in values}) != 3:
            raise ValueError('As alternativas devem ser diferentes.')
        return [v.strip() for v in values]

    @field_validator('image')
    @classmethod
    def raster_image(cls, value):
        if not value:
            return value
        from io import BytesIO
        from PIL import Image
        if not value.startswith(('data:image/png;base64,', 'data:image/jpeg;base64,', 'data:image/webp;base64,')):
            raise ValueError('Use PNG, JPEG ou WebP incorporado (até 2 MB).')
        try:
            raw = base64.b64decode(value.split(',', 1)[1], validate=True)
            if len(raw) > 2 * 1024 * 1024:
                raise ValueError('Imagem acima de 2 MB.')
            with Image.open(BytesIO(raw)) as im:
                if im.width * im.height > 24000000 or im.format not in ('PNG', 'JPEG', 'WEBP'):
                    raise ValueError('Imagem inválida ou acima de 24 megapixels.')
                expected = {'PNG': 'image/png', 'JPEG': 'image/jpeg', 'WEBP': 'image/webp'}[im.format]
                if not value.startswith('data:' + expected + ';'):
                    raise ValueError('O tipo da imagem não corresponde ao arquivo.')
                im.verify()
        except Exception as exc:
            raise ValueError('Imagem inválida; use PNG, JPEG ou WebP até 2 MB e 24 megapixels.') from exc
        return value


@lru_cache(maxsize=1)
def assets():
    return (json.loads((ASSETS / 'components.json').read_text(encoding='utf-8')),
            (ASSETS / 'astryx.css').read_text(encoding='utf-8'),
            (ASSETS / 'LICENSE.txt').read_text(encoding='utf-8'))


